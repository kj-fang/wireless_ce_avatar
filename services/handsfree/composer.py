"""
Comment-draft composer: turns a CaseAnalysis into the IPS comment text.

Two renderings:
  * plain  — what the reviewer edits in the queue UI (also the Selenium
             fallback paste body)
  * html   — rich-text for the REST field Core_IPS_Rich_Comment__c

Every draft carries AI_MARKER so the ledger / prior-comment scan can detect
our own posts and never double-comment a case.
"""

from __future__ import annotations

import html as _html
from typing import Optional

from .runner import CaseAnalysis, IncidentReport

AI_MARKER = "[AI-Avatar preliminary analysis]"
_FOOTER = ("Generated by Intel Wireless CE Avatar (AI). "
           "Please verify before sharing conclusions with the customer.")


def _norm_key(k: str) -> str:
    """Normalize a JSON key for tolerant lookup: the triage LLM oscillates
    between 'Issue summary' / 'Issue_summary' / 'issue summary' etc."""
    return "".join(ch for ch in str(k).lower() if ch.isalnum())


def _get_norm(d: dict, key: str):
    """Fetch d[key] tolerating spacing/underscore/case variations."""
    if not isinstance(d, dict):
        return None
    want = _norm_key(key)
    for k, v in d.items():
        if _norm_key(k) == want:
            return v
    return None


def _triage_sections(triage: dict) -> list[tuple[str, list[str]]]:
    """Flatten the analyze_desc JSON into (title, lines) sections."""
    out: list[tuple[str, list[str]]] = []
    summary = _get_norm(triage, "Issue summary") or {}
    if isinstance(summary, dict):
        for key in ("Symptom", "Repro Steps", "Other Information"):
            val = _get_norm(summary, key)
            if isinstance(val, list) and val:
                out.append((key, [str(v) for v in val if str(v).strip()]))
            elif isinstance(val, str) and val.strip():
                out.append((key, [val.strip()]))
    action = _get_norm(triage, "Next action") or {}
    if isinstance(action, dict):
        rec = _get_norm(action, "Recommendation")
        if isinstance(rec, list) and rec:
            out.append(("Recommended next steps / questions",
                        [str(v) for v in rec if str(v).strip()]))
        elif isinstance(rec, str) and rec.strip():
            out.append(("Recommended next steps / questions", [rec.strip()]))
    return out


def _customer_tz(analysis: CaseAnalysis) -> str:
    """The customer's time zone name as the runner saw it (recorded on the
    alignment / mismatch), else read from the log's system_info.txt."""
    for d in (getattr(analysis, "time_alignment", None),
              getattr(analysis, "time_mismatch", None)):
        if isinstance(d, dict) and d.get("customer_tz"):
            return str(d["customer_tz"])
    if getattr(analysis, "log_path", ""):
        try:
            from utils.timezone_utils import get_effective_timezone
            return get_effective_timezone(analysis.log_path) or ""
        except Exception:
            pass
    return ""


def _anchor_label(anchor: str) -> str:
    from .runner import ANCHOR_LABELS
    return ANCHOR_LABELS.get(anchor or "", anchor or "unknown")


def _incident_lines(inc: IncidentReport, customer_tz: str = "") -> list[str]:
    lines: list[str] = []
    rep = inc.report or {}
    if inc.issue_time:
        log_t = getattr(inc, "issue_time_log", "") or ""
        cust_t = getattr(inc, "issue_time_customer", "") or ""
        if log_t and log_t != cust_t:
            # Two clocks: what the customer reported vs the same moment in
            # the decoded log (decoder host clock).
            lines.append(f"Incident time: {inc.issue_time} (customer"
                         + (f", {customer_tz}" if customer_tz else "")
                         + f") = {log_t} (in the log)")
        else:
            lines.append(f"Incident time: {inc.issue_time}")
    if rep.get("root_cause_summary"):
        lines.append(f"Root cause: {rep['root_cause_summary']}")
    if rep.get("confidence_score") is not None:
        lines.append(f"Confidence: {rep['confidence_score']}/100")
    skills = rep.get("involved_skills") or []
    if skills:
        lines.append("Analysis areas: " + ", ".join(str(s) for s in skills))
    actions = rep.get("recommended_actions") or []
    if actions:
        lines.append("Recommended actions:")
        lines.extend(f"  - {a}" for a in actions)
    return lines


# Customer-facing ask per missing-info item (fixed text, no LLM — these can
# post publicly via the request_info / request_logs replies).
_INFO_ASKS = {
    "issue_description": ("a clearer description of the issue — what exactly "
                          "fails, and expected vs actual behavior"),
    "issue_time": ("the exact date and time (with timezone) when the issue "
                   "occurred, matching the attached logs"),
    "repro_steps": ("step-by-step reproduction instructions and how often "
                    "the issue reproduces"),
}


# Tag line distinguishing customer-facing first-response/request comments
# from analysis comments in the approve-time duplicate scan: one of each may
# post on a case, never two of the same kind.
CHECKLIST_TAG = "[AI-Avatar first-response]"


def _checklist_fills(analysis: CaseAnalysis) -> dict:
    """Fills computed by the orchestrator (deterministic + LLM) when present;
    otherwise a deterministic-only build so composing never needs an LLM."""
    fills = getattr(analysis, "checklist_fills", None)
    if fills:
        return fills
    # llm=None: deterministic fills only. build_fills also settles
    # analysis.issue_subcategory, which the renderers read afterwards — the
    # items and the section label/triage steps must use the same pick.
    from .checklist import build_fills
    return build_fills(analysis)


def _checklist_body(analysis: CaseAnalysis) -> list[str]:
    """The pre-filled domain checklist — the customer gets it ONCE per case
    (first round); later request replies carry only their targeted ask."""
    if getattr(analysis, "first_response_done", False):
        return []
    from .checklist import FALLBACK_DOMAIN, render_checklist_body
    domain = getattr(analysis, "issue_domain", "") or FALLBACK_DOMAIN
    return render_checklist_body(domain, _checklist_fills(analysis),
                                 getattr(analysis, "issue_subcategory", ""))


def _info_ask_bullets(analysis: CaseAnalysis, numbered: bool = False) -> list[str]:
    out = []
    for n, m in enumerate((analysis.missing_info or []), 1):
        ask = _INFO_ASKS.get(m.get("item"))
        if ask:
            out.append(f"  {n}. {ask}," if numbered else f"  - {ask}")
    if out and not numbered:
        out[-1] = out[-1].rstrip(",")
    return out


def _request_info_lines(analysis: CaseAnalysis) -> list[str]:
    """Customer-facing reply asking for missing case information. Fixed
    template (no LLM text): this draft posts PUBLICLY once approved."""
    parts = [
        "Hello,",
        "",
        "Thank you for reporting this issue"
        + (f" ({analysis.subject})" if analysis.subject else "") + ".",
        "",
        "To start the analysis we need some additional information about the "
        "case. Could you please provide:",
    ]
    parts += _info_ask_bullets(analysis)
    checklist = _checklist_body(analysis)
    if checklist:
        parts += [""] + checklist
    parts += ["",
              "We will proceed with the analysis as soon as this information "
              "is available. Thank you!"]
    return parts


def _request_dump_lines(analysis: CaseAnalysis) -> list[str]:
    """BSOD case without a crash dump: ask for the kernel/memory dump — the
    PotatoFarm BSOD parser works on it; a WRT log is not what a BSOD needs.
    Fixed template (posts PUBLICLY once approved)."""
    parts = [
        "Hello,",
        "",
        "Thank you for reporting this issue"
        + (f" ({analysis.subject})" if analysis.subject else "") + ".",
        "",
        "To root-cause a BSOD we need the Windows crash dump of the failure — "
        "it is what the kernel debugger analysis works on, and we could not "
        "find one attached to this case.",
        "",
        "Could you please:",
        "  1. Attach the kernel memory dump of the crash (C:\\Windows\\MEMORY.DMP), "
        "or the minidumps from C:\\Windows\\Minidump, zipped — one archive per "
        "failing system / SKU is ideal,",
        "  2. Note the bug check (stop) code shown on the blue screen for each dump,",
        "  3. Attach the archive(s) to this case.",
        "",
        "We will start the analysis as soon as the dump is available. Thank you!",
    ]
    tail = parts.pop()
    info = _info_ask_bullets(analysis)
    if info:
        parts += ["",
                  "In addition, to speed up the analysis please also provide:"]
        parts += info
    checklist = _checklist_body(analysis)
    if checklist:
        parts += [""] + checklist
    parts += ["", tail]
    return parts


def _bsod_lines(analysis: CaseAnalysis) -> list[str]:
    """Private reviewer note for the BSOD branch: what went to the BSOD share
    and whether PotatoFarm was triggered (its analysis arrives by e-mail)."""
    b = getattr(analysis, "bsod", None) or {}
    parts = [
        f"Case {analysis.case_nbr}"
        + (f" — {analysis.subject}" if analysis.subject else ""),
        "BSOD case — a crash dump is attached, so no issue time was requested; "
        "the dump went through Avatar's BSOD flow (PotatoFarm parser).",
    ]
    if b.get("bugcheck_codes"):
        parts.append(f"Bug check codes (IPS form): {b['bugcheck_codes']}")
    parts.append("Dump upload(s): " + ", ".join(b.get("dumps") or []))
    if b.get("failed"):
        parts.append("Download GAVE UP (stalled twice — fetch manually or ask for a "
                     "smaller upload): " + ", ".join(b["failed"]))
    if analysis.mode == "bsod_pending":
        last = next((p_ for p_ in reversed(b.get("previous") or [])
                     if p_.get("attachments")), {})
        parts.append(
            f"Already submitted on {last.get('submitted_at', '?')} "
            f"({', '.join(last.get('attachments') or [])}); no new dump upload since.")
    else:
        if b.get("dumps_path"):
            parts.append(f"Downloaded to: {b['dumps_path']}")
        if b.get("submitted"):
            parts.append(
                "Submitted to the PotatoFarm BSOD parser (result also e-mailed to "
                f"{b.get('email') or '?'}).")
        elif b.get("skipped"):
            parts.append(f"PotatoFarm NOT triggered: {b['skipped']}. Submit manually "
                         "from Avatar (BSOD toggle) if needed.")
        else:
            parts.append(f"PotatoFarm submission FAILED (HTTP {b.get('status') or '?'}): "
                         f"{b.get('detail') or 'no detail'}. Submit manually from Avatar "
                         "(BSOD toggle).")
    results = b.get("results") or []
    if results:
        from .bsod import assessment
        parts += ["", "PotatoFarm BSOD parser result"
                  + (f" ({b['result_html']})" if b.get("result_html") else "") + ":"]
        for r in results:
            parts.append(
                f"  - {r.get('dump')}: bugcheck 0x{r.get('bugcheck_code')} "
                f"{r.get('bugcheck_str')}; bucket {r.get('failure_bucket_id') or '?'}; "
                f"process {r.get('process_name') or '?'}; dump time {r.get('dump_time') or '?'}")
            parts.append(
                f"      Intel Wi-Fi driver: {'AT FAULT' if r.get('wifi_fault') else 'not at fault'}"
                f"{' (on the stack)' if r.get('driver_on_stack') else ''}; "
                f"BT driver: {'AT FAULT' if r.get('bt_fault') else 'not at fault'}; "
                f"driver {r.get('driver_version') or '?'} ({r.get('driver_branch') or '?'}); "
                f"verifier {'on' if r.get('verifier') else 'off'}; "
                f"FW asserts {r.get('fw_asserts') if r.get('fw_asserts') is not None else '?'}"
                + ("; DUMP CORRUPTED" if r.get("corrupted") else "")
                + (f"; JIRA {r['jira_id']}" if r.get("jira_id") else ""))
            if r.get("stack"):
                parts.append("      stack: " + " <- ".join(r["stack"][:6]))
        parts.append(f"  Assessment: {assessment(results)}")
    elif b.get("submitted") or analysis.mode == "bsod_pending":
        parts.append(
            "PotatoFarm result not in the dump folder yet (bsod_parse_output.json / "
            "bsod_report.html appear there when the parser finishes; the next round "
            "picks them up).")
    parts.append("")
    return parts


def _request_logs_lines(analysis: CaseAnalysis) -> list[str]:
    """Customer-facing reply asking for the missing WRT logs. Deliberately a
    fixed template (no LLM text): this draft posts PUBLICLY once approved."""
    if getattr(analysis, "log_request_reason", "") == "no_dump":
        return _request_dump_lines(analysis)
    if getattr(analysis, "log_request_reason", "") == "unreadable_archive":
        # Archive selection crashed or the download failed twice — the upload
        # is likely corrupted/incomplete; ask for a re-upload.
        name = f" ({analysis.chosen_attachment})" if analysis.chosen_attachment else ""
        missing = (f"we were unable to download or open the attached log "
                   f"archive{name} — the file may be corrupted or the upload "
                   "incomplete, so please RE-UPLOAD the log archive")
    elif getattr(analysis, "log_request_reason", "") == "log_not_covering":
        # The log decoded fine but was captured at another time: the issue
        # time is what the analysis anchors on (policy 2026-10-07).
        tm = analysis.time_mismatch or {}
        name = f" ({analysis.chosen_attachment})" if analysis.chosen_attachment else ""
        if tm.get("log_first_customer"):
            # The log's range in the CUSTOMER's clock (the runner shifted the
            # decoder-host times) — never show the customer Taiwan times.
            tz = tm.get("customer_tz") or ""
            covers = (f"{tm['log_first_customer']} – {tm.get('log_last_customer', '?')} "
                      f"(your local time{', ' + tz if tz else ''})")
        else:
            covers = f"{tm.get('log_first', '?')} – {tm.get('log_last', '?')}"
        missing = (f"we checked the attached archive{name}: the WRT log inside "
                   f"covers {covers}, "
                   f"but the reported issue time is {', '.join(tm.get('issue_times', []))}"
                   + (f" (we also tried {tm['also_tried']} other capture folder(s) "
                      "in the archive)" if tm.get("also_tried") else "")
                   + ". Please provide a WRT log captured at the issue time, or "
                   "confirm the exact failure time if it differs from the one reported")
    elif analysis.chosen_attachment:
        # An archive was attached, but after extraction it held no driver
        # WPP ETL. Say what it DID contain: an autologger capture with
        # firmware / event logs is not "no WRT logs" (00991735).
        found = getattr(analysis, "archive_contents", None) or {}
        parts_found = [label for key, label in (
            ("fw", "firmware (wrt-fw) traces"), ("event_logs", "Windows event logs"),
            ("bt", "Bluetooth traces")) if found.get(key)]
        missing = (f"we checked the attached archive ({analysis.chosen_attachment})"
                   + (f" — it contains {', '.join(parts_found)}" if parts_found else "")
                   + " but no Intel Wi-Fi driver WPP log (WifiDriverIHVSession.etl), "
                   "which is the trace the analysis needs")
    else:
        missing = "we could not find a WRT log archive attached to this case"
    parts = [
        "Hello,",
        "",
        "Thank you for reporting this issue"
        + (f" ({analysis.subject})" if analysis.subject else "") + ".",
        "",
        "To root-cause it we need the Intel wireless driver WRT logs covering "
        f"the failure — they are critical for the analysis, and {missing}.",
        "",
        "Could you please:",
        "  1. Reproduce the issue and note the exact failure time,",
        "  2. Collect the WRT logs from the affected system,",
        "  3. Attach the resulting archive (.zip/.7z/.rar) to this case "
        "along with the failure timestamp.",
        "",
        "We will start the analysis as soon as the logs are available. "
        "Thank you!",
    ]
    # One combined public reply: targeted info asks (when any), then the full
    # pre-filled domain checklist, then the closing line.
    tail = parts.pop()
    info = _info_ask_bullets(analysis)
    if info:
        parts += ["",
                  "In addition, to speed up the analysis please also provide:"]
        parts += info
    checklist = _checklist_body(analysis)
    if checklist:
        parts += [""] + checklist
    parts += ["", tail]
    return parts


def compose_plain(analysis: CaseAnalysis) -> str:
    """Plain-text draft (editable in the review UI)."""
    parts: list[str] = [AI_MARKER, ""]

    if analysis.mode in ("request_logs", "request_info", "first_response"):
        # Customer-facing first-response family: tagged so the approve-time
        # duplicate scan distinguishes them from analysis comments.
        parts.insert(1, CHECKLIST_TAG)
        if analysis.mode == "request_logs":
            parts.extend(_request_logs_lines(analysis))
        elif analysis.mode == "request_info":
            parts.extend(_request_info_lines(analysis))
        else:
            from .checklist import render_first_response
            parts.extend(render_first_response(analysis, _checklist_fills(analysis)))
        text = "\n".join(parts)
        while "\n\n\n" in text:
            text = text.replace("\n\n\n", "\n\n")
        return text.strip() + "\n"

    if analysis.mode == "waiting_customer":
        # Private reviewer note only: the thread shows Intel is waiting on
        # the customer, so no analysis ran and no request was drafted.
        parts += [
            f"Case {analysis.case_nbr}"
            + (f" — {analysis.subject}" if analysis.subject else ""),
            "Waiting on the customer — no analysis run, no request sent.",
            f"Next action — customer: {analysis.next_action or '(not stated)'}",
            "The issue-time / log checks run once the customer replies.",
            "",
            _FOOTER,
        ]
        return "\n".join(parts).strip() + "\n"

    # Time-coverage warning first — the reviewer must see it before the
    # findings, because findings from a log that does not cover the reported
    # issue time may describe a DIFFERENT occurrence.
    customer_tz = _customer_tz(analysis)
    tm = analysis.time_mismatch or {}
    if tm.get("log_first"):
        reported = f"Reported issue time: {', '.join(tm.get('issue_times', []))}"
        mapped = [m for m in (tm.get("issue_times_log") or []) if m]
        if mapped and mapped != tm.get("issue_times"):
            reported += (f" (customer{', ' + customer_tz if customer_tz else ''}) = "
                         f"{', '.join(mapped)} in the log's clock")
        covers = f"Attached WRT log covers {tm['log_first']} – {tm.get('log_last')}"
        if tm.get("log_first_customer"):
            covers += (f" (log clock) = {tm['log_first_customer']} – "
                       f"{tm.get('log_last_customer')} (customer clock"
                       + (f", {customer_tz}" if customer_tz else "")
                       + f"; {tm.get('offset', '?')} via {_anchor_label(tm.get('anchor', ''))})")
        parts += [
            "*** TIME MISMATCH — the attached log does NOT cover the reported "
            "issue time ***",
            f"{reported}. {covers}.",
        ]
        if tm.get("yb_assert_override"):
            parts.append(
                "Yellow-bang case: assert(s) "
                + ", ".join(tm["yb_assert_override"])
                + " found in this log — analysis continued on the assert "
                "evidence despite the time mismatch.")
        else:
            parts.append("Log time is not the same as the issue time — please "
                         "help provide a WRT log captured at the issue time.")
        parts.append("")

    # How the customer's clock was aligned to the log's (reviewer check):
    # only worth a line when the two clocks actually differ.
    ta = getattr(analysis, "time_alignment", None) or {}
    if ta.get("offset") and ta.get("offset") not in ("+00:00", "-00:00"):
        parts += [
            f"Clock alignment: customer {ta.get('customer_time')}"
            + (f" ({customer_tz})" if customer_tz else "")
            + f" = log {ta.get('log_time')}; offset {ta['offset']} via "
            f"{_anchor_label(ta.get('anchor', ''))}.",
            "",
        ]

    # BSOD branch: what went to the BSOD share / PotatoFarm (private note).
    if analysis.mode in ("bsod_submitted", "bsod_pending"):
        parts += _bsod_lines(analysis)

    # Where the case stands after reading the comment thread: who acts next
    # and what the step is (reader output; Private-to-Intel drafts only).
    next_action = getattr(analysis, "next_action", "") or ""
    if next_action:
        from .case_reader import ACTION_OWNER_LABELS
        who = ACTION_OWNER_LABELS.get(getattr(analysis, "action_owner", ""),
                                      "owner unclear")
        parts += [f"Next action — {who}: {next_action}", ""]

    # Echo knowledge-base advice on what to ask / do next (Private-to-Intel
    # drafts only — never in a customer-facing reply).
    adv = getattr(analysis, "echo_advice", None) or {}
    if adv.get("status") == "answered" and adv.get("answer"):
        ans = str(adv["answer"]).strip()
        if len(ans) > 1500:
            ans = ans[:1500] + " …[truncated — full text in analysis details]"
        parts += ["Echo knowledge base — suggested next steps (for reference; "
                  "may contain internal knowledge — check before sharing):", ans, ""]

    # Case-info gaps that didn't block the analysis: give the reviewer a
    # forwardable clarification request (this draft posts Private-to-Intel).
    if analysis.missing_info:
        parts.append("Request for clarification — please ask the customer to provide:")
        for m in analysis.missing_info:
            ask = _INFO_ASKS.get(m.get("item"))
            if not ask:
                continue
            reason = (m.get("reason") or "").strip()
            parts.append(f"  - {ask}" + (f" ({reason})" if reason else ""))
        parts.append("")

    if analysis.mode == "full" and analysis.incidents:
        parts.append(f"Automated log analysis for case {analysis.case_nbr}"
                     + (f" — {analysis.subject}" if analysis.subject else ""))
        if analysis.issue_type:
            parts.append(f"Issue classification: {analysis.issue_type}")
        parts.append("")
        reported = [i for i in analysis.incidents if i.report]
        for n, inc in enumerate(reported, 1):
            if len(reported) > 1:
                parts.append(f"--- Incident {n}/{len(reported)} ---")
            parts.extend(_incident_lines(inc, customer_tz))
            md = (inc.report or {}).get("markdown_summary") or ""
            if md:
                parts.append("")
                parts.append(md.strip())
            parts.append("")
    else:
        # Triage-only: description-level assessment + what we need from the OEM.
        parts.append(f"Automated triage for case {analysis.case_nbr}"
                     + (f" — {analysis.subject}" if analysis.subject else ""))
        if analysis.issue_type:
            parts.append(f"Issue classification: {analysis.issue_type}")
        if analysis.error:
            parts.append(f"(Full log analysis not run: {analysis.error})")
        parts.append("")
        for title, lines in _triage_sections(analysis.triage):
            parts.append(f"{title}:")
            parts.extend(f"  - {ln}" for ln in lines)
            parts.append("")

    # Echo knowledge-base insights (assert / yellow-bang root causes).
    answered = [i for i in (analysis.echo_insights or [])
                if isinstance(i, dict) and i.get("answer")]
    if answered:
        parts.append("Knowledge base insights (Echo):")
        for ins in answered:
            head = (f"Assert {ins.get('code')}" if ins.get("kind") == "assert"
                    else "Yellow bang")
            answer = str(ins["answer"]).strip()
            if len(answer) > 1500:
                answer = answer[:1500] + " …[truncated — full text in analysis details]"
            parts.append(f"[{head}] {answer}")
            parts.append("")

    parts.append(_FOOTER)
    # Collapse accidental double blank lines.
    text = "\n".join(parts)
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text.strip() + "\n"


def compose_html(plain_text: str) -> str:
    """Rich-text rendering for Core_IPS_Rich_Comment__c: escape + <br/>.
    (Salesforce rich text accepts a limited HTML subset; simple line breaks
    keep the plain and rich renderings identical after human edits.)"""
    escaped = _html.escape(plain_text)
    return "<p>" + escaped.replace("\n", "<br/>") + "</p>"


def compose(analysis: CaseAnalysis) -> dict:
    """Returns {"plain": str, "html": str, "confidence": int|None}."""
    plain = compose_plain(analysis)
    best = analysis.best_incident
    return {
        "plain": plain,
        "html": compose_html(plain),
        "confidence": best.confidence if best else None,
    }
